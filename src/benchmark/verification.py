"""
SWE-bench Verification Module

Provides functionality to verify patches and run tests for SWE-bench tasks.
"""

import json
import logging
import os
import re
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)


@dataclass
class TestResult:
    """Result of running tests."""
    test_name: str
    passed: bool
    error_message: Optional[str] = None
    output: Optional[str] = None


@dataclass
class VerificationResult:
    """Result of verifying a patch."""
    resolved: bool
    fail_to_pass_results: List[TestResult]
    pass_to_pass_results: List[TestResult]
    total_passed: int
    total_failed: int
    resolution_rate: float
    details: Dict[str, Any]


class PatchVerifier:
    """
    Verifies patches against SWE-bench gold patches and test requirements.
    """
    
    def __init__(self, task_workspace: Path):
        """
        Initialize the verifier.
        
        Args:
            task_workspace: Path to the task workspace
        """
        self.workspace = task_workspace
    
    def apply_patch(self, patch: str) -> Tuple[bool, str]:
        """
        Apply a patch to the workspace.
        
        Args:
            patch: Git diff format patch
            
        Returns:
            Tuple of (success, error_message)
        """
        try:
            result = subprocess.run(
                ["git", "apply", "--allow-empty"],
                input=patch,
                cwd=self.workspace,
                capture_output=True,
                text=True,
                timeout=60
            )
            
            if result.returncode == 0:
                return True, ""
            else:
                return False, result.stderr
                
        except subprocess.TimeoutExpired:
            return False, "Patch application timed out"
        except Exception as e:
            return False, str(e)
    
    def extract_modified_files(self, patch: str) -> List[str]:
        """
        Extract list of files modified by a patch.
        
        Args:
            patch: Git diff format patch
            
        Returns:
            List of modified file paths
        """
        pattern = r'^[\+\-]{3} [ab]/(.+)$'
        files = set()
        
        for line in patch.split('\n'):
            match = re.match(pattern, line)
            if match:
                files.add(match.group(1))
        
        return list(files)
    
    def compare_patches(
        self,
        generated_patch: str,
        gold_patch: str
    ) -> Dict[str, Any]:
        """
        Compare a generated patch with the gold patch.
        
        Args:
            generated_patch: The patch generated by AutoDev
            gold_patch: The expected gold patch
            
        Returns:
            Dictionary with comparison metrics
        """
        gen_files = set(self.extract_modified_files(generated_patch))
        gold_files = set(self.extract_modified_files(gold_patch))
        
        return {
            "generated_files": list(gen_files),
            "gold_files": list(gold_files),
            "files_overlap": list(gen_files & gold_files),
            "files_only_in_generated": list(gen_files - gold_files),
            "files_only_in_gold": list(gold_files - gold_files),
            "file_overlap_ratio": (
                len(gen_files & gold_files) / len(gold_files) 
                if gold_files else 0
            )
        }
    
    def run_test(
        self,
        test_command: str,
        test_name: str,
        timeout: int = 300
    ) -> TestResult:
        """
        Run a single test.
        
        Args:
            test_command: Command to run the test
            test_name: Name of the test
            timeout: Timeout in seconds
            
        Returns:
            TestResult with outcome
        """
        try:
            result = subprocess.run(
                test_command,
                shell=True,
                cwd=self.workspace,
                capture_output=True,
                text=True,
                timeout=timeout
            )
            
            passed = result.returncode == 0
            return TestResult(
                test_name=test_name,
                passed=passed,
                output=result.stdout + result.stderr,
                error_message=None if passed else result.stderr
            )
            
        except subprocess.TimeoutExpired:
            return TestResult(
                test_name=test_name,
                passed=False,
                error_message=f"Test timed out after {timeout}s"
            )
        except Exception as e:
            return TestResult(
                test_name=test_name,
                passed=False,
                error_message=str(e)
            )
    
    def run_pytest_tests(
        self,
        test_files: List[str],
        timeout: int = 600
    ) -> List[TestResult]:
        """
        Run pytest tests.
        
        Args:
            test_files: List of test file patterns
            timeout: Overall timeout
            
        Returns:
            List of TestResults
        """
        results = []
        
        for test_pattern in test_files:
            try:
                result = subprocess.run(
                    ["python", "-m", "pytest", test_pattern, "-v", "--tb=short"],
                    cwd=self.workspace,
                    capture_output=True,
                    text=True,
                    timeout=timeout
                )
                
                # Parse pytest output
                output = result.stdout + result.stderr
                passed = result.returncode == 0
                
                results.append(TestResult(
                    test_name=test_pattern,
                    passed=passed,
                    output=output,
                    error_message=None if passed else output[-1000:]
                ))
                
            except subprocess.TimeoutExpired:
                results.append(TestResult(
                    test_name=test_pattern,
                    passed=False,
                    error_message=f"Tests timed out after {timeout}s"
                ))
            except Exception as e:
                results.append(TestResult(
                    test_name=test_pattern,
                    passed=False,
                    error_message=str(e)
                ))
        
        return results
    
    def verify_resolution(
        self,
        fail_to_pass: List[str],
        pass_to_pass: List[str],
        test_patch: Optional[str] = None
    ) -> VerificationResult:
        """
        Verify if the issue is resolved by running tests.
        
        Args:
            fail_to_pass: Tests that should pass after fix
            pass_to_pass: Tests that should still pass
            test_patch: Optional test changes to apply
            
        Returns:
            VerificationResult with details
        """
        # Apply test patch if provided
        if test_patch:
            self.apply_patch(test_patch)
        
        # Run FAIL_TO_PASS tests
        fail_to_pass_results = []
        for test in fail_to_pass:
            # Try to determine test type and run appropriately
            if test.startswith("test_") or "::test" in test:
                result = self.run_pytest_tests([test])
                fail_to_pass_results.extend(result)
            else:
                # Generic test command
                result = self.run_test(test, test)
                fail_to_pass_results.append(result)
        
        # Run PASS_TO_PASS tests
        pass_to_pass_results = []
        for test in pass_to_pass:
            if test.startswith("test_") or "::test" in test:
                result = self.run_pytest_tests([test])
                pass_to_pass_results.extend(result)
            else:
                result = self.run_test(test, test)
                pass_to_pass_results.append(result)
        
        # Calculate results
        total_passed = sum(1 for r in fail_to_pass_results if r.passed)
        total_passed += sum(1 for r in pass_to_pass_results if r.passed)
        total_failed = sum(1 for r in fail_to_pass_results if not r.passed)
        total_failed += sum(1 for r in pass_to_pass_results if not r.passed)
        
        # Resolution requires all FAIL_TO_PASS tests to pass
        fail_to_pass_passed = all(r.passed for r in fail_to_pass_results)
        pass_to_pass_passed = all(r.passed for r in pass_to_pass_results)
        
        resolved = fail_to_pass_passed and pass_to_pass_passed
        
        total_tests = len(fail_to_pass_results) + len(pass_to_pass_results)
        resolution_rate = total_passed / total_tests if total_tests > 0 else 0
        
        return VerificationResult(
            resolved=resolved,
            fail_to_pass_results=fail_to_pass_results,
            pass_to_pass_results=pass_to_pass_results,
            total_passed=total_passed,
            total_failed=total_failed,
            resolution_rate=resolution_rate,
            details={
                "fail_to_pass_passed": fail_to_pass_passed,
                "pass_to_pass_passed": pass_to_pass_passed,
                "fail_to_pass_total": len(fail_to_pass_results),
                "pass_to_pass_total": len(pass_to_pass_results)
            }
        )


class MockVerifier:
    """
    Mock verifier for testing the harness without actual test execution.
    """
    
    def __init__(self, success_rate: float = 0.25):
        """
        Initialize mock verifier.
        
        Args:
            success_rate: Probability of mock resolution success
        """
        self.success_rate = success_rate
    
    def verify_resolution(
        self,
        fail_to_pass: List[str],
        pass_to_pass: List[str],
        **kwargs
    ) -> VerificationResult:
        """Return mock verification result."""
        import random
        
        resolved = random.random() < self.success_rate
        
        return VerificationResult(
            resolved=resolved,
            fail_to_pass_results=[
                TestResult(test_name=t, passed=resolved)
                for t in fail_to_pass
            ],
            pass_to_pass_results=[
                TestResult(test_name=t, passed=True)
                for t in pass_to_pass
            ],
            total_passed=len(fail_to_pass) + len(pass_to_pass) if resolved else len(pass_to_pass),
            total_failed=0 if resolved else len(fail_to_pass),
            resolution_rate=1.0 if resolved else len(pass_to_pass) / (len(fail_to_pass) + len(pass_to_pass)),
            details={"mock": True}
        )
